#[test]
fn a_second_request_for_one_symmetry_does_not_build_a_second_chain() {
    let symmetry = riemann_generators();
    let mut cache = ChainCache::new();
    assert!(cache.is_empty());

    let first = cache
        .chain(4, &symmetry)
        .expect("width 4 generators")
        .clone();
    assert_eq!(cache.computations(), 1);
    assert_eq!(cache.len(), 1);

    for _ in 0..8 {
        let again = cache.chain(4, &symmetry).expect("width 4 generators");
        assert_eq!(again.render(), first.render());
    }

    assert_eq!(
        cache.computations(),
        1,
        "the cache built a chain for a symmetry it already held"
    );
    assert_eq!(cache.len(), 1);
}

#[test]
fn a_different_symmetry_is_a_different_entry() {
    let mut cache = ChainCache::new();
    let riemann = riemann_generators();

    cache.chain(4, &riemann).expect("width 4 generators");

    // The near miss is the point of this test. Two generator sets that differ
    // by one generator, and two that differ only in the order the same
    // generators are given in, are three different keys, because the chain is a
    // function of the order as well as of the set.
    let one_fewer: Vec<Permutation> = riemann.iter().skip(1).cloned().collect();
    let reordered: Vec<Permutation> = riemann.iter().rev().cloned().collect();
    let wider = symmetric_generators(5);

    cache.chain(4, &one_fewer).expect("width 4 generators");
    cache.chain(4, &reordered).expect("width 4 generators");
    cache.chain(5, &wider).expect("width 5 generators");

    assert_eq!(cache.computations(), 4);
    assert_eq!(cache.len(), 4);

    // Two chains that describe the same group from different generator orders
    // agree about the group and are not required to be the same chain.
    let by_order = cache
        .chain(4, &riemann)
        .expect("width 4 generators")
        .order();
    let by_reordered = cache
        .chain(4, &reordered)
        .expect("width 4 generators")
        .order();
    assert_eq!(by_order, by_reordered);
    assert_eq!(cache.computations(), 4);
}

#[test]
fn a_refused_symmetry_is_not_stored_and_is_refused_again() {
    let mut cache = ChainCache::new();
    let mismatched = vec![Permutation::new(vec![1, 0, 2]).expect("a permutation of three points")];

    for _ in 0..3 {
        let refused = cache.chain(4, &mismatched);
        assert_eq!(
            refused.err(),
            Some(PermutationError::WidthMismatch { left: 4, right: 3 })
        );
    }

    assert!(cache.is_empty());
    assert_eq!(cache.computations(), 0);
}

#[test]
fn a_generator_of_another_width_is_refused_rather_than_padded() {
    let refused = StabiliserChain::new(
        4,
        vec![
            Permutation::new(vec![1, 0, 2, 3]).expect("a permutation of four points"),
            Permutation::new(vec![1, 0, 2]).expect("a permutation of three points"),
        ],
    );

    assert_eq!(
        refused.err(),
        Some(PermutationError::WidthMismatch { left: 4, right: 3 })
    );

    // The narrow identity is the case that decides whether the refusal is the
    // constructor's or an accident of where the first composition happens. Every
    // other mismatched generator reaches a composition and is refused by
    // `Permutation::then` whether or not anything looked at the widths first.
    // This one is skipped as an identity before it reaches one, so a
    // constructor that did not compare widths would accept it and answer a
    // question about a group on four points from a generator on three.
    let narrow_identity = StabiliserChain::new(4, vec![Permutation::identity(3)]);

    assert_eq!(
        narrow_identity.err(),
        Some(PermutationError::WidthMismatch { left: 4, right: 3 })
    );
}

#[test]
fn a_candidate_of_another_width_is_refused_rather_than_answered() {
    let chain = StabiliserChain::new(4, riemann_generators()).expect("width 4 generators");
    let narrow = Permutation::new(vec![1, 0, 2]).expect("a permutation of three points");

    assert_eq!(
        chain.contains(&narrow).err(),
        Some(PermutationError::WidthMismatch { left: 4, right: 3 })
    );

    // The trivial group is where the comparison is the only thing standing
    // between the caller and an answer. There is no level to strip through, so
    // nothing composes, and a membership test that did not look at the width
    // would compare a permutation of three points against the identity on four
    // and report the mismatch as a mathematical no.
    let trivial = StabiliserChain::new(4, Vec::new()).expect("the trivial group on four points");

    assert_eq!(
        trivial.contains(&narrow).err(),
        Some(PermutationError::WidthMismatch { left: 4, right: 3 })
    );
}

#[test]
fn an_order_that_does_not_fit_is_refused_and_the_orbit_lengths_are_not() {
    // The symmetric group on 35 points. 34! is inside a u128 and 35! is not, so
    // this is the first symmetric group whose order the product cannot carry,
    // and the check is that it says so rather than wrapping.
    let width = 35;
    let chain = StabiliserChain::new(width, symmetric_generators(width))
        .expect("the generators are on this width");

    assert_eq!(chain.order(), None);

    let lengths = chain.basic_orbit_lengths();
    assert_eq!(lengths, (2..=width).rev().collect::<Vec<usize>>());
    assert_eq!(chain.base(), (0..width - 1).collect::<Vec<usize>>());

    // One point fewer is 34!, which fits, and it is the near miss: a check that
    // refused every large group would pass the assertion above for the wrong
    // reason.
    let smaller = StabiliserChain::new(width - 1, symmetric_generators(width - 1))
        .expect("the generators are on this width");
    assert_eq!(smaller.order(), Some(factorial(width - 1)));
}

/// The group, written out, from its generators.
///
/// Breadth first over compositions with the generators until nothing new
/// appears. Nothing here is shared with the chain: it does not know what a base
/// is, it never strips, and it holds the elements in a sorted list so that
/// membership is a comparison of permutations and not of anything the chain
/// computed.
fn closure(width: usize, generators: &[Permutation]) -> Vec<Permutation> {
    let mut elements = vec![Permutation::identity(width)];
    let mut frontier = 0;
    while frontier < elements.len() {
        let element = elements[frontier].clone();
        frontier += 1;
        for generator in generators {
            let product = element
                .then(generator)
                .expect("the generators are on the closure width");
            if !elements.contains(&product) {
                elements.push(product);
            }
        }
    }
    elements.sort();
    elements
}

/// Every permutation of `width` points, in the order of `docs/normal-form.md`.
fn every_permutation(width: usize) -> Vec<Permutation> {
    let mut all = Vec::new();
    let mut images: Vec<usize> = (0..width).collect();
    loop {
        all.push(Permutation::new(images.clone()).expect("a rearrangement of 0..width"));
        if !next_arrangement(&mut images) {
            break;
        }
    }
    all.sort();
    all
}

/// The next arrangement in ascending order, or `false` where there is none.
fn next_arrangement(images: &mut [usize]) -> bool {
    if images.len() < 2 {
        return false;
    }
    let mut pivot = images.len() - 1;
    while pivot > 0 && images[pivot - 1] >= images[pivot] {
        pivot -= 1;
    }
    if pivot == 0 {
        return false;
    }
    let mut swap = images.len() - 1;
    while images[swap] <= images[pivot - 1] {
        swap -= 1;
    }
    images.swap(pivot - 1, swap);
    images[pivot..].reverse();
    true
}

/// The adjacent transpositions, which generate the symmetric group.
fn symmetric_generators(width: usize) -> Vec<Permutation> {
    (1..width)
        .map(|point| transposition(width, point - 1, point))
        .collect()
}

/// The three-cycles through the first two points, which generate the
/// alternating group for a width of at least three.
fn alternating_generators(width: usize) -> Vec<Permutation> {
    (2..width)
        .map(|point| cycle(width, &[0, 1, point]))
        .collect()
}

fn transposition(width: usize, left: usize, right: usize) -> Permutation {
    cycle(width, &[left, right])
}

/// The permutation sending each point of `points` to the next, and the last to
/// the first.
fn cycle(width: usize, points: &[usize]) -> Permutation {
    let mut images: Vec<usize> = (0..width).collect();
    for (position, &point) in points.iter().enumerate() {
        let next = points[(position + 1) % points.len()];
        images[point] = next;
    }
    Permutation::new(images).expect("a cycle over distinct points is a permutation")
}

/// The same permutation acting on the points from `offset` upwards.
fn shift(permutation: &Permutation, offset: usize, width: usize) -> Permutation {
    let mut images: Vec<usize> = (0..width).collect();
    for (point, &image) in permutation.images().iter().enumerate() {
        images[point + offset] = image + offset;
    }
    Permutation::new(images).expect("a shifted permutation of disjoint points")
}

/// The same permutation on more points, fixing the ones it gains.
fn widen(permutation: &Permutation, width: usize) -> Permutation {
    let mut images: Vec<usize> = (0..width).collect();
    for (point, &image) in permutation.images().iter().enumerate() {
        images[point] = image;
    }
    Permutation::new(images).expect("a widened permutation fixes the points it gains")
}

/// The slot symmetry of the Riemann tensor, without the first Bianchi identity.
///
/// Antisymmetric in the first pair, antisymmetric in the second, and symmetric
/// under exchanging the pairs. The signs those symmetries carry are not here:
/// they are a property of the declaration and not of the permutation group, and
/// #25 is where a declaration carries them.
fn riemann_generators() -> Vec<Permutation> {
    vec![
        Permutation::new(vec![1, 0, 2, 3]).expect("a transposition of the first pair"),
        Permutation::new(vec![0, 1, 3, 2]).expect("a transposition of the second pair"),
        Permutation::new(vec![2, 3, 0, 1]).expect("the exchange of the two pairs"),
    ]
}

fn factorial(width: usize) -> u128 {
    (1..=width as u128).product()
}

fn product(lengths: &[usize]) -> Option<u128> {
    let mut total: u128 = 1;
    for &length in lengths {
        total = total.checked_mul(length as u128)?;
    }
    Some(total)
}

fn render_generators(generators: &[Permutation]) -> String {
    generators
        .iter()
        .map(|generator| format!("{:?}", generator.images()))
        .collect::<Vec<String>>()
        .join(", ")
}

/// How many random generator sets each property draws.
const CASES: usize = 60;

/// A deterministic source of small generator sets.
///
/// Xorshift with a multiply, seeded from a constant, in the shape
/// `tests/permutation.rs` uses and for the reason given at the top of this
/// file. The stream is fixed, so a failure reported above is reproduced by
/// running that test again and is the same case on every machine.
struct Source {
    state: u64,
}

impl Source {
    /// The next sixteen hexadecimal digits of the fractional part of pi after
    /// the ones `tests/permutation.rs` seeds from, so the two files draw
    /// different streams rather than the same one twice.
    const SEED: u64 = 0x1319_8A2E_0370_7344;

    fn new() -> Self {
        Source { state: Self::SEED }
    }

    fn next(&mut self) -> u64 {
        let mut state = self.state;
        state ^= state >> 12;
        state ^= state << 25;
        state ^= state >> 27;
        self.state = state;
        state.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    /// A value below `bound`, and zero where the bound is zero.
    fn below(&mut self, bound: usize) -> usize {
        if bound == 0 {
            return 0;
        }
        (self.next() % bound as u64) as usize
    }

    fn permutation(&mut self, width: usize) -> Permutation {
        let mut images: Vec<usize> = (0..width).collect();
        for index in (1..width).rev() {
            let other = self.below(index + 1);
            images.swap(index, other);
        }
        Permutation::new(images).expect("a shuffle of 0..width is a permutation of it")
    }

    /// One to three generators on `width` points.
    ///
    /// A small number on purpose: two generators drawn at random on five points
    /// are the whole symmetric group more often than not, and a set that
    /// generates a proper subgroup is the interesting input for a chain.
    fn generator_set(&mut self, width: usize) -> Vec<Permutation> {
        let count = 1 + self.below(3);
        (0..count).map(|_| self.permutation(width)).collect()
    }
}
