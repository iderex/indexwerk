//! The stabiliser chain of #21, checked against a definition rather than
//! against another implementation.
//!
//! # What the reference is
//!
//! For a group small enough to write out, the answer can be computed from first
//! principles: close the generators under composition until nothing new
//! appears, and the result is the group. Its size is the order, and membership
//! is a lookup. [`closure`] below is that computation, and it is deliberately
//! naive, because a reference that shares an optimisation with the thing it
//! checks shares the mistake in it.
//!
//! This is not the oracle of #23. That issue asks for one covering orbits and
//! stabilisers as well, with property tests over random generator sets and a
//! stated boundary where enumeration stops being usable. What is here is the
//! part #21's own conditions name: a brute-force order and an exhaustive
//! membership answer, for the cases below.
//!
//! # Where the random generator sets come from
//!
//! From the generator at the bottom of this file, for the reason
//! `tests/permutation.rs` gives for its own: this workspace has no third-party
//! dependency, and every entry added to one is a supply chain entry the policy
//! of #38 has to account for. The two sources are separate because an
//! integration test file is its own crate and sharing one would mean a module
//! both files reach into, and because what is drawn here is a set of generators
//! rather than a single permutation.

use indexwerk_core::permutation::{Permutation, PermutationError};
use indexwerk_core::stabiliser_chain::{ChainCache, StabiliserChain};

/// The widest group this file enumerates by brute force.
///
/// Six points is 720 permutations, which is what the exhaustive membership test
/// walks per case, and the whole file runs well inside the time budget of a
/// suite that runs on every change. Seven would be 5040 and eight 40320, and
/// the cost is in the closure rather than in the walk: the closure composes
/// every element with every generator until it stops growing. Where the
/// boundary is exactly, and what is done above it, is #23.
const ENUMERABLE_WIDTH: usize = 6;

/// A named case, its generators, and the order it is known to have.
struct Case {
    name: &'static str,
    width: usize,
    generators: Vec<Permutation>,
    known_order: u128,
}

/// The standard cases #21 names, in the order it names them.
///
/// The orders are the definitions of the groups rather than measurements of
/// them. `|S_n| = n!` and `|A_n| = n!/2` and `|C_n| = n` and the order of a
/// direct product is the product of the orders, all in Rotman, *An Introduction
/// to the Theory of Groups*, 4th edition, Springer 1995, chapter 3. The Riemann
/// case is the one that is not a definition and it is the reason this list
/// exists: the slot symmetry generated by the antisymmetry of each pair and the
/// exchange of the two pairs is the wreath product of two groups of order two,
/// which has order eight, and the first Bianchi identity is not in it because it
/// is a multi-term identity and not a slot symmetry at all
/// (`docs/adr/0003-single-term-only.md`).
fn standard_cases() -> Vec<Case> {
    let mut cases = Vec::new();

    for width in 1..=ENUMERABLE_WIDTH {
        cases.push(Case {
            name: "symmetric group",
            width,
            generators: symmetric_generators(width),
            known_order: factorial(width),
        });
    }

    for width in 3..=ENUMERABLE_WIDTH {
        cases.push(Case {
            name: "alternating group",
            width,
            generators: alternating_generators(width),
            known_order: factorial(width) / 2,
        });
    }

    for width in 1..=ENUMERABLE_WIDTH {
        cases.push(Case {
            name: "cyclic group",
            width,
            generators: vec![cycle(width, &(0..width).collect::<Vec<usize>>())],
            known_order: width as u128,
        });
    }

    for left in 1..=3 {
        for right in 1..=3 {
            let mut generators = symmetric_generators(left);
            for generator in symmetric_generators(right) {
                generators.push(shift(&generator, left, left + right));
            }
            let generators = generators
                .iter()
                .map(|generator| widen(generator, left + right))
                .collect();
            cases.push(Case {
                name: "direct product of two symmetric groups",
                width: left + right,
                generators,
                known_order: factorial(left) * factorial(right),
            });
        }
    }

    cases.push(Case {
        name: "Riemann slot symmetry",
        width: 4,
        generators: riemann_generators(),
        known_order: 8,
    });

    cases.push(Case {
        name: "trivial group, given no generators",
        width: 4,
        generators: Vec::new(),
        known_order: 1,
    });

    cases.push(Case {
        name: "trivial group, given only the identity",
        width: 4,
        generators: vec![Permutation::identity(4)],
        known_order: 1,
    });

    cases
}

#[test]
fn the_order_from_the_chain_is_the_order_of_the_enumerated_group() {
    for case in standard_cases() {
        let chain = StabiliserChain::new(case.width, case.generators.clone())
            .expect("the generators are on the case width");
        let enumerated = closure(case.width, &case.generators);

        assert_eq!(
            chain.order(),
            Some(enumerated.len() as u128),
            "{} on {} points: the chain and the enumeration disagree",
            case.name,
            case.width
        );
    }
}

#[test]
fn the_order_from_the_chain_is_the_order_the_case_is_known_to_have() {
    for case in standard_cases() {
        let chain = StabiliserChain::new(case.width, case.generators.clone())
            .expect("the generators are on the case width");

        assert_eq!(
            chain.order(),
            Some(case.known_order),
            "{} on {} points: the chain disagrees with the stated order",
            case.name,
            case.width
        );
    }
}

#[test]
fn the_order_from_the_chain_is_the_order_of_a_randomly_generated_group() {
    let mut source = Source::new();
    for _ in 0..CASES {
        let width = 2 + source.below(ENUMERABLE_WIDTH - 1);
        let generators = source.generator_set(width);

        let chain = StabiliserChain::new(width, generators.clone())
            .expect("the generators are on the drawn width");
        let enumerated = closure(width, &generators);

        assert_eq!(
            chain.order(),
            Some(enumerated.len() as u128),
            "the chain and the enumeration disagree on {}",
            render_generators(&generators)
        );
    }
}

#[test]
fn membership_is_answered_correctly_for_every_permutation_of_the_width() {
    for case in standard_cases() {
        if case.width > ENUMERABLE_WIDTH {
            continue;
        }
        let chain = StabiliserChain::new(case.width, case.generators.clone())
            .expect("the generators are on the case width");
        let enumerated = closure(case.width, &case.generators);

        // Every permutation of the width, not a sample of them, so the answer
        // is checked on the non-elements as well. A membership test that
        // answered yes to everything would pass a test that only fed it
        // elements, and that is the failure this walk exists to catch.
        for candidate in every_permutation(case.width) {
            let expected = enumerated.contains(&candidate);
            let answered = chain
                .contains(&candidate)
                .expect("the candidate is on the chain width");

            assert_eq!(
                answered,
                expected,
                "{} on {} points: membership of {} was answered {}",
                case.name,
                case.width,
                render_generators(std::slice::from_ref(&candidate)),
                answered
            );
        }
    }
}

#[test]
fn membership_is_answered_correctly_for_a_randomly_generated_group() {
    let mut source = Source::new();
    for _ in 0..CASES {
        let width = 2 + source.below(4);
        let generators = source.generator_set(width);

        let chain = StabiliserChain::new(width, generators.clone())
            .expect("the generators are on the drawn width");
        let enumerated = closure(width, &generators);

        for candidate in every_permutation(width) {
            let expected = enumerated.contains(&candidate);
            let answered = chain
                .contains(&candidate)
                .expect("the candidate is on the chain width");
            assert_eq!(
                answered,
                expected,
                "membership disagreed on {} for the group {}",
                render_generators(std::slice::from_ref(&candidate)),
                render_generators(&generators)
            );
        }
    }
}

#[test]
fn every_strong_generator_is_an_element_and_the_chain_is_consistent_with_itself() {
    for case in standard_cases() {
        let chain = StabiliserChain::new(case.width, case.generators.clone())
            .expect("the generators are on the case width");

        for generator in chain.strong_generators() {
            assert!(
                chain
                    .contains(&generator)
                    .expect("a strong generator is on the chain width"),
                "{}: a strong generator is not an element of the group it generates",
                case.name
            );
        }

        // The base is what the chain is a chain of, so a level's generators all
        // fix every base point above that level. This is the property the
        // strip in the membership test relies on, and it is the one that goes
        // wrong when a residue is added to too few levels.
        for (index, level) in chain.levels().iter().enumerate() {
            for higher in chain.base().into_iter().take(index) {
                for generator in level.generators() {
                    assert_eq!(
                        generator.image(higher),
                        Some(higher),
                        "{}: a generator of level {index} moves the base point {higher} above it",
                        case.name
                    );
                }
            }
            assert_eq!(
                level.orbit().first(),
                Some(&level.base()),
                "{}: an orbit does not start at its own base point",
                case.name
            );
        }

        assert_eq!(
            chain.order(),
            product(&chain.basic_orbit_lengths()),
            "{}: the order and the orbit lengths disagree",
            case.name
        );
    }
}

#[test]
fn the_transversal_takes_the_base_point_where_it_says_it_does() {
    for case in standard_cases() {
        let chain = StabiliserChain::new(case.width, case.generators.clone())
            .expect("the generators are on the case width");

        for level in chain.levels() {
            for &point in level.orbit() {
                let element = level
                    .transversal(point)
                    .expect("a point of the orbit has a transversal element");
                assert_eq!(
                    element.image(level.base()),
                    Some(point),
                    "{}: the transversal element for {point} does not reach it",
                    case.name
                );
                assert!(
                    chain
                        .contains(element)
                        .expect("a transversal element is on the chain width"),
                    "{}: a transversal element is not in the group",
                    case.name
                );
            }
            for point in 0..case.width {
                assert_eq!(
                    level.transversal(point).is_some(),
                    level.orbit().contains(&point),
                    "{}: the transversal and the orbit disagree about {point}",
                    case.name
                );
            }
        }
    }
}

#[test]
fn the_same_generators_in_the_same_order_produce_a_byte_identical_chain() {
    for case in standard_cases() {
        let first = StabiliserChain::new(case.width, case.generators.clone())
            .expect("the generators are on the case width");
        let second = StabiliserChain::new(case.width, case.generators.clone())
            .expect("the generators are on the case width");

        assert_eq!(
            first.render().as_bytes(),
            second.render().as_bytes(),
            "{} on {} points: two builds from one input rendered differently",
            case.name,
            case.width
        );
        assert_eq!(first, second);
    }
}

